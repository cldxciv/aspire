#!/usr/bin/env node
/**
 * DEVELOPMENT seed for the auth database (D-029).
 *
 * Creates, idempotently, four demo accounts: one admin, two students and one parent
 * (linked to the first student), each with a RANDOMLY GENERATED password. The
 * credentials are written only to `.data/dev-credentials.txt` (git-ignored) and are
 * never printed. Refuses to run when NODE_ENV=production.
 *
 *   npm run auth:seed              create missing demo accounts, keep existing ones
 *   npm run auth:seed -- --reset   also give the existing demo accounts new passwords
 *
 * Database: AUTH_DB_PATH (default .data/aspire.sqlite). Run through the npm script: it
 * passes `--conditions=react-server` so the `server-only` markers in src/lib resolve.
 */
import { chmodSync, existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, relative, resolve } from "node:path";

import { generateTemporaryPassword, hashPassword } from "../src/lib/auth/password.ts";
import { recordAudit } from "../src/lib/db/audit.ts";
import { openDatabase, resolveDbPath, withTransaction } from "../src/lib/db/connection.ts";
import { insertParentLink } from "../src/lib/db/links.ts";
import { deleteUserSessions } from "../src/lib/db/sessions.ts";
import { findUserByLoginId, insertUser, setUserPassword } from "../src/lib/db/users.ts";

if (process.env.NODE_ENV === "production") {
  console.error("auth:seed refuses to run with NODE_ENV=production (it creates demo accounts). Nothing was changed.");
  process.exit(1);
}

const ACCOUNTS = [
  { role: "admin", loginId: "dev.admin", displayName: "Demo Admin (dev)" },
  { role: "student", loginId: "dev.student1", displayName: "Demo Student One (dev)" },
  { role: "student", loginId: "dev.student2", displayName: "Demo Student Two (dev)" },
  { role: "parent", loginId: "dev.parent", displayName: "Demo Parent (dev)" },
];
const PARENT_LINK = { parent: "dev.parent", student: "dev.student1" };

const cwd = process.cwd();
const reset = process.argv.includes("--reset");
const credentialsPath = resolve(cwd, ".data", "dev-credentials.txt");

/** login id → password from an earlier run (tab-separated: role, login id, password). */
function readKnownPasswords() {
  const known = new Map();
  if (!existsSync(credentialsPath)) return known;
  for (const line of readFileSync(credentialsPath, "utf8").split(/\r?\n/)) {
    if (!line || line.startsWith("#")) continue;
    const [, loginId, password] = line.split("\t");
    if (loginId && password) known.set(loginId, password);
  }
  return known;
}

const dbPath = resolveDbPath();
const db = openDatabase(dbPath);
const known = readKnownPasswords();
const now = Date.now();
const rows = [];
const counts = { created: 0, kept: 0, reset: 0 };
const notes = [];

for (const account of ACCOUNTS) {
  const existing = findUserByLoginId(db, account.loginId);
  if (existing && existing.role !== account.role) {
    notes.push(`${account.loginId} already exists with another role; left unchanged.`);
    continue;
  }
  if (existing && !reset) {
    const password = known.get(account.loginId);
    if (password) {
      rows.push({ ...account, password });
      counts.kept += 1;
    } else {
      notes.push(`${account.loginId} exists but its password is not in the credentials file; run with --reset.`);
    }
    continue;
  }

  const password = generateTemporaryPassword();
  const passwordHash = await hashPassword(password);
  withTransaction(db, () => {
    if (existing) {
      setUserPassword(db, existing.id, passwordHash, false, now);
      deleteUserSessions(db, existing.id);
      recordAudit(db, { actorId: null, action: "seed.password_reset", target: existing.id, now });
    } else {
      const user = insertUser(db, {
        role: account.role,
        displayName: account.displayName,
        loginId: account.loginId,
        passwordHash,
        mustChangePassword: false,
        now,
      });
      recordAudit(db, {
        actorId: null,
        action: "seed.user_create",
        target: user.id,
        details: { role: user.role, loginId: user.loginId },
        now,
      });
    }
  });
  rows.push({ ...account, password });
  if (existing) counts.reset += 1;
  else counts.created += 1;
}

const parent = findUserByLoginId(db, PARENT_LINK.parent);
const student = findUserByLoginId(db, PARENT_LINK.student);
if (parent?.role === "parent" && student?.role === "student") {
  withTransaction(db, () => {
    if (insertParentLink(db, { parentId: parent.id, studentId: student.id, createdBy: null, now })) {
      recordAudit(db, { actorId: null, action: "seed.link_add", target: parent.id, details: { studentId: student.id }, now });
    }
  });
}
db.close();

mkdirSync(dirname(credentialsPath), { recursive: true, mode: 0o700 });
const lines = [
  "# Aspire — DEV-ONLY demo accounts, generated by `npm run auth:seed`.",
  `# Updated ${new Date(now).toISOString()}. Database: ${relative(cwd, dbPath) || dbPath}`,
  "# Local development only. Never commit, share, paste or reuse these passwords.",
  `# The parent account is linked to ${PARENT_LINK.student}.`,
  "# role\tlogin id\tpassword",
  ...rows.map((row) => `${row.role}\t${row.loginId}\t${row.password}`),
  "",
];
writeFileSync(credentialsPath, lines.join("\n"), { encoding: "utf8", mode: 0o600 });
try {
  chmodSync(credentialsPath, 0o600);
} catch {
  // Not supported on every file system (e.g. Windows); the folder is git-ignored either way.
}

console.log(
  `Demo accounts: ${counts.created} created, ${counts.kept} kept, ${counts.reset} given new passwords.` +
    ` ${PARENT_LINK.parent} is linked to ${PARENT_LINK.student}.`,
);
for (const note of notes) console.log(`Note: ${note}`);
console.log(`Credentials were written to ${relative(cwd, credentialsPath)} (git-ignored). They are not printed here.`);
